def get_slides(conn: sqlite3.Connection, pitchbook_id: int) -> list[dict[str, Any]]:
    slides = query(conn, "SELECT * FROM slides WHERE pitchbook_id = ? ORDER BY seq", (pitchbook_id,))
    for slide in slides:
        slide["payload"] = load_json(slide["payload"], {})
        slide["is_pinned"] = bool(slide["is_pinned"])
    return slides


def list_pitchbooks(conn: sqlite3.Connection) -> list[dict[str, Any]]:
    return query(conn, """
        SELECT p.id, p.title, p.subtitle, p.client_name, p.banker, p.status,
               p.created_at, p.updated_at, c.ticker, c.name AS target_name,
               (SELECT COUNT(*) FROM slides s WHERE s.pitchbook_id = p.id) AS slide_count,
               (SELECT COUNT(*) FROM evidence e WHERE e.pitchbook_id = p.id) AS evidence_count
        FROM pitchbooks p LEFT JOIN companies c ON c.id = p.target_company_id
        ORDER BY p.updated_at DESC
    """)


def get_pitchbook(conn: sqlite3.Connection, pitchbook_id: int) -> dict[str, Any] | None:
    book = query_one(conn, """
        SELECT p.*, c.ticker, c.name AS target_name, c.sector
        FROM pitchbooks p LEFT JOIN companies c ON c.id = p.target_company_id
        WHERE p.id = ?
    """, (pitchbook_id,))
    if not book:
        return None
    book["assumptions"] = load_json(book["assumptions"], {})
    book["slides"] = get_slides(conn, pitchbook_id)
    book["comps"] = comp_tickers_for(conn, pitchbook_id)
    book["evidence"] = query(conn, """
        SELECT e.*, d.title, d.doc_type, d.published_at, c.ticker
        FROM evidence e LEFT JOIN documents d ON d.id = e.document_id
        LEFT JOIN companies c ON c.id = d.company_id
        WHERE e.pitchbook_id = ? ORDER BY e.id
    """, (pitchbook_id,))
    return book


