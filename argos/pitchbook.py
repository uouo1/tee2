    ("disclaimer", "Disclaimer"),
    ("executive_summary", "Executive summary"),
    ("company_overview", "Company overview"),
    ("market_overview", "Market overview"),
    ("financial_performance", "Historical and projected financial performance"),
    ("valuation_summary", "Valuation summary — football field"),
    ("trading_comps", "Trading comparables"),
    ("precedent_transactions", "Precedent transactions"),
    ("dcf", "Discounted cash flow analysis"),
    ("dcf_sensitivity", "DCF sensitivity"),
