def _slide_evidence(ctx: dict[str, Any]) -> dict[str, Any]:
    conn, pitchbook_id = ctx["conn"], ctx["pitchbook_id"]
    rows = query(conn, """
        SELECT e.id, e.quote, e.note, e.created_at, e.slide_id, e.document_id,
               d.title, d.doc_type, d.published_at, d.source, c.ticker
        FROM evidence e
        LEFT JOIN documents d ON d.id = e.document_id
        LEFT JOIN companies c ON c.id = d.company_id
        WHERE e.pitchbook_id = ? ORDER BY e.id
    """, (pitchbook_id,))
    return {
        "title": "Appendix — sources and evidence",
        "subtitle": f"{len(rows)} pinned item(s) from the research corpus",
        "payload": {"items": rows},
    }


