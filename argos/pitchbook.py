def create_pitchbook(
    conn: sqlite3.Connection,
    *,
    title: str,
    target_ticker: str,
    comp_tickers: Sequence[str] | None = None,
    client_name: str | None = None,
    subtitle: str | None = None,
    banker: str | None = None,
    assumptions: dict[str, Any] | None = None,
) -> int:
    """Create a pitch book for a target and generate its slides."""
    target = query_one(conn, "SELECT id, name, sector FROM companies WHERE ticker = ?", (target_ticker.upper(),))
    if not target:
        raise ValueError(f"unknown target ticker: {target_ticker}")

    if not comp_tickers:
        comp_tickers = suggest_comps(conn, target_ticker)

    pitchbook_id = insert(conn, "pitchbooks", {
        "title": title,
        "subtitle": subtitle or f"Strategic alternatives for {target['name']}",
        "client_name": client_name,
        "target_company_id": target["id"],
        "banker": banker,
        "status": "draft",
        "assumptions": dump_json(assumptions or {}),
        "created_at": _now(),
        "updated_at": _now(),
    })
    for ticker in comp_tickers:
        company = query_one(conn, "SELECT id FROM companies WHERE ticker = ?", (ticker.upper(),))
        if company and company["id"] != target["id"]:
            conn.execute(
                "INSERT OR IGNORE INTO comp_members (pitchbook_id, company_id, kind) VALUES (?, ?, 'trading')",
                (pitchbook_id, company["id"]),
            )
    conn.commit()
    rebuild_slides(conn, pitchbook_id)
    return pitchbook_id


def suggest_comps(conn: sqlite3.Connection, target_ticker: str, *, limit: int = 6) -> list[str]:
    """Suggest a comp set: same sector, closest in revenue scale.

    Size proximity (log revenue distance) is the screen that matters most for a
    trading comps set; sector keeps the business model honest.
    """
    target = valuation.company_metrics(conn, target_ticker)
    if not target:
        return []
    target_revenue = max(1.0, float(target["latest_actual"]["revenue"] or 1.0))
    candidates = query(conn, """
        SELECT c.ticker, f.revenue
        FROM companies c
        JOIN financials f ON f.company_id = c.id AND f.is_estimate = 0
        WHERE c.sector IS ? AND c.ticker != ?
        GROUP BY c.id HAVING f.fiscal_year = MAX(f.fiscal_year)
    """, (target["sector"], target_ticker.upper()))
    import math

    ranked = sorted(
        candidates,
        key=lambda r: abs(math.log(max(1.0, float(r["revenue"] or 1.0)) / target_revenue)),
    )
    return [r["ticker"] for r in ranked[:limit]]


def comp_tickers_for(conn: sqlite3.Connection, pitchbook_id: int) -> list[str]:
    return [r["ticker"] for r in query(conn, """
        SELECT c.ticker FROM comp_members cm JOIN companies c ON c.id = cm.company_id
        WHERE cm.pitchbook_id = ? AND cm.kind = 'trading' ORDER BY c.ticker
    """, (pitchbook_id,))]


