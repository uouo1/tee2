def update_slide(
    conn: sqlite3.Connection, slide_id: int, *,
    title: str | None = None, subtitle: str | None = None,
    payload: dict[str, Any] | None = None, pin: bool | None = None,
) -> dict[str, Any] | None:
    """Edit a slide. Any edit pins it unless told otherwise."""
    slide = query_one(conn, "SELECT * FROM slides WHERE id = ?", (slide_id,))
    if not slide:
        return None
    sets: dict[str, Any] = {}
    if title is not None:
        sets["title"] = title
    if subtitle is not None:
        sets["subtitle"] = subtitle
    if payload is not None:
        merged = {**load_json(slide["payload"], {}), **payload}
        sets["payload"] = dump_json(merged)
    sets["is_pinned"] = 1 if (pin is None or pin) else 0
    conn.execute(
        f"UPDATE slides SET {', '.join(f'{k} = ?' for k in sets)} WHERE id = ?",
        [*sets.values(), slide_id],
    )
    conn.execute("UPDATE pitchbooks SET updated_at = ? WHERE id = ?", (_now(), slide["pitchbook_id"]))
    conn.commit()
    updated = query_one(conn, "SELECT * FROM slides WHERE id = ?", (slide_id,))
    if updated:
        updated["payload"] = load_json(updated["payload"], {})
        updated["is_pinned"] = bool(updated["is_pinned"])
    return updated


def reorder_slides(conn: sqlite3.Connection, pitchbook_id: int, slide_ids: Sequence[int]) -> list[dict[str, Any]]:
    for seq, slide_id in enumerate(slide_ids):
        conn.execute("UPDATE slides SET seq = ? WHERE id = ? AND pitchbook_id = ?", (seq, slide_id, pitchbook_id))
    conn.execute("UPDATE pitchbooks SET updated_at = ? WHERE id = ?", (_now(), pitchbook_id))
    conn.commit()
    return get_slides(conn, pitchbook_id)


def add_evidence(
    conn: sqlite3.Connection, pitchbook_id: int, *,
    quote: str, document_id: int | None = None, chunk_id: int | None = None,
    slide_id: int | None = None, note: str | None = None,
) -> dict[str, Any]:
    """Pin a passage from the research corpus onto a deck (optionally a slide).

    This is the join between the two halves of the product: the quote keeps its
    document and chunk ids, so the appendix and every citation stay traceable.
    """
    if chunk_id and not quote:
        chunk = query_one(conn, "SELECT text, document_id FROM chunks WHERE id = ?", (chunk_id,))
        if chunk:
            quote = chunk["text"]
            document_id = document_id or chunk["document_id"]
    if not (quote or "").strip():
        raise ValueError("evidence requires a quote")
    evidence_id = insert(conn, "evidence", {
        "pitchbook_id": pitchbook_id,
        "slide_id": slide_id,
        "document_id": document_id,
        "chunk_id": chunk_id,
        "quote": quote.strip()[:2000],
        "note": note,
        "created_at": _now(),
    })
    conn.execute("UPDATE pitchbooks SET updated_at = ? WHERE id = ?", (_now(), pitchbook_id))
    conn.commit()
    _refresh_evidence_slide(conn, pitchbook_id)
    return query_one(conn, "SELECT * FROM evidence WHERE id = ?", (evidence_id,)) or {}


def delete_evidence(conn: sqlite3.Connection, evidence_id: int) -> bool:
    row = query_one(conn, "SELECT pitchbook_id FROM evidence WHERE id = ?", (evidence_id,))
    if not row:
        return False
    conn.execute("DELETE FROM evidence WHERE id = ?", (evidence_id,))
    conn.commit()
    _refresh_evidence_slide(conn, row["pitchbook_id"])
    return True


def _refresh_evidence_slide(conn: sqlite3.Connection, pitchbook_id: int) -> None:
    """Keep the appendix in step with pinned evidence without a full rebuild."""
    slide = query_one(conn, "SELECT id, is_pinned FROM slides WHERE pitchbook_id = ? AND kind = 'evidence_appendix'", (pitchbook_id,))
    if not slide or slide["is_pinned"]:
        return
    built = _slide_evidence({"conn": conn, "pitchbook_id": pitchbook_id})
    conn.execute(
        "UPDATE slides SET title = ?, subtitle = ?, payload = ? WHERE id = ?",
        (built["title"], built.get("subtitle"), dump_json(built["payload"]), slide["id"]),
    )
    conn.commit()


def set_comps(conn: sqlite3.Connection, pitchbook_id: int, tickers: Sequence[str]) -> list[str]:
    conn.execute("DELETE FROM comp_members WHERE pitchbook_id = ? AND kind = 'trading'", (pitchbook_id,))
    target = query_one(conn, "SELECT target_company_id FROM pitchbooks WHERE id = ?", (pitchbook_id,))
    for ticker in tickers:
        company = query_one(conn, "SELECT id FROM companies WHERE ticker = ?", (ticker.upper(),))
        if company and (not target or company["id"] != target["target_company_id"]):
            conn.execute(
                "INSERT OR IGNORE INTO comp_members (pitchbook_id, company_id, kind) VALUES (?, ?, 'trading')",
                (pitchbook_id, company["id"]),
            )
    conn.commit()
    rebuild_slides(conn, pitchbook_id)
    return comp_tickers_for(conn, pitchbook_id)


def set_assumptions(conn: sqlite3.Connection, pitchbook_id: int, assumptions: dict[str, Any]) -> dict[str, Any]:
    book = query_one(conn, "SELECT assumptions FROM pitchbooks WHERE id = ?", (pitchbook_id,))
    if not book:
        raise ValueError(f"unknown pitchbook: {pitchbook_id}")
    merged = {**load_json(book["assumptions"], {}), **{k: v for k, v in assumptions.items() if v not in (None, "")}}
    conn.execute("UPDATE pitchbooks SET assumptions = ?, updated_at = ? WHERE id = ?", (dump_json(merged), _now(), pitchbook_id))
    conn.commit()
    rebuild_slides(conn, pitchbook_id)
    return merged


def delete_pitchbook(conn: sqlite3.Connection, pitchbook_id: int) -> bool:
    cur = conn.execute("DELETE FROM pitchbooks WHERE id = ?", (pitchbook_id,))
    conn.commit()
    return cur.rowcount > 0
