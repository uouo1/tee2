# frozen_string_literal: true

require "open3"

# Pitch book generation — the other half of the application.
#
# A pitch book here is not a template with blanks. Each slide is a structured
# payload computed from the same database the research module indexes, which is
# what makes the two halves one product:
#
# * the executive summary quotes the corpus and keeps the document id;
# * the market overview is the trending-theme model, not a stock paragraph;
# * the valuation slides are live outputs of Valuation;
# * every claim can carry pinned evidence, and the appendix is generated from it.
#
# Slides render identically in the web UI, the HTML deck, the PDF and the PPTX
# export because all of them read the same payload. Port of argos/pitchbook.py;
# the slide builders live in pitchbooks/slides/*.rb (one module per kind) and
# carry the audit's prose corrections (docs/RAILS_PORT.md items 16–22).
module Pitchbooks
  SLIDE_ORDER = [
    %w[cover Cover],
    %w[disclaimer Disclaimer],
    ["executive_summary", "Executive summary"],
    ["company_overview", "Company overview"],
    ["market_overview", "Market overview"],
    ["financial_performance", "Historical and projected financial performance"],
    ["valuation_summary", "Valuation summary — football field"],
    ["trading_comps", "Trading comparables"],
    ["precedent_transactions", "Precedent transactions"],
    ["dcf", "Discounted cash flow analysis"],
    ["dcf_sensitivity", "DCF sensitivity"],
    ["buyers", "Potential counterparties"],
    ["process", "Process considerations and next steps"],
    ["evidence_appendix", "Appendix — sources and evidence"]
  ].map(&:freeze).freeze

  DISCLAIMER =
    "This document has been prepared for discussion purposes only and does not constitute an offer, " \
    "a recommendation or advice. It is based on information generated by the Argos research corpus and on " \
    "publicly available information believed to be reliable; no representation is made as to its accuracy or " \
    "completeness. Financial projections are illustrative, depend on assumptions stated herein and will differ " \
    "from actual results. Recipients should perform their own analysis and consult their own advisers."

  QUOTE_LIMIT = 2000

  module_function

  # ----------------------------------------------------------------- creation

  # Create a pitch book for a target and generate its slides.
  # Raises ArgumentError for an unknown target (Python's ValueError).
  def create!(title:, target_ticker:, comp_tickers: nil, client_name: nil, subtitle: nil, banker: nil, assumptions: nil)
    target = Company.find_ticker(target_ticker.to_s.strip)
    raise ArgumentError, "unknown target ticker: #{target_ticker}" unless target

    comp_tickers = Array(comp_tickers).map { |t| t.to_s.strip.upcase }.reject(&:empty?)
    comp_tickers = suggest_comps(target.ticker) if comp_tickers.empty?

    book = nil
    Pitchbook.transaction do
      book = Pitchbook.create!(
        title: title.presence || "Project #{target.ticker}",
        subtitle: subtitle.presence || "Strategic alternatives for #{target.name}",
        client_name: client_name.presence,
        target_company_id: target.id,
        banker: banker.presence,
        status: "draft",
        assumptions: JSON.generate(clean_assumptions(assumptions))
      )
      write_comps(book, comp_tickers)
      rebuild_slides!(book)
    end
    book.reload
  end

  # Suggest a comp set: same sector, closest in revenue scale.
  #
  # Size proximity (log revenue distance) is the screen that matters most for a
  # trading comps set; sector keeps the business model honest.
  def suggest_comps(target_ticker, limit: 6)
    target = Valuation.company_metrics(target_ticker)
    return [] unless target

    target_revenue = [1.0, (target.dig(:latest_actual, :revenue) || 1.0).to_f].max
    target_revenue = 1.0 if target_revenue.zero?
    candidates = Company.where(sector: target[:sector]).where.not(ticker: target[:ticker]).includes(:financials).filter_map do |company|
      latest = company.financials.select { |f| !f.is_estimate && f.period_type != "LTM" }.max_by(&:fiscal_year)
      latest && [company.ticker, latest.revenue]
    end
    # Stable on ties, like Python's sorted().
    candidates.each_with_index
              .sort_by { |(_, revenue), i| [(Math.log([1.0, (revenue || 1.0).to_f].max / target_revenue)).abs, i] }
              .first(limit).map { |(ticker, _), _| ticker }
  end

  def comp_tickers_for(pitchbook)
    pitchbook.comp_tickers
  end

  # -------------------------------------------------------------- slide build

  # Regenerate every non-pinned slide from current data.
  #
  # Slides a banker has hand-edited are marked pinned and survive a rebuild —
  # regenerating the deck must never silently discard someone's wording. A
  # pinned cover keeps its wording but gets a fresh stamp: the stamp is a fact
  # about the build, not prose.
  def rebuild_slides!(pitchbook)
    pitchbook = Pitchbook.find(pitchbook) unless pitchbook.is_a?(Pitchbook)
    target = pitchbook.target_company
    raise ArgumentError, "pitchbook has no target company" unless target

    ticker = target.ticker
    comps = pitchbook.comp_tickers
    metrics = Valuation.company_metrics(ticker)
    raise ArgumentError, "no financials loaded for #{ticker}" unless metrics

    field = Valuation.football_field(ticker, comps, assumptions: pitchbook.assumptions_hash)
    profile = Analytics.company_profile(ticker) || {}
    ctx = Slides::Context.new(
      pitchbook: pitchbook, ticker: ticker, comps: comps, field: field,
      metrics: metrics, profile: profile, stamp: stamp_for(metrics, comps)
    )

    Pitchbook.transaction do
      pinned = pitchbook.slides.where(is_pinned: true).index_by(&:kind)
      # delete_all, not destroy: evidence pointing at a regenerated slide is
      # unlinked by the foreign key (ON DELETE SET NULL), exactly as in Python.
      Slide.where(pitchbook_id: pitchbook.id, is_pinned: false).delete_all
      SLIDE_ORDER.each_with_index do |(kind, default_title), seq|
        if (slide = pinned[kind])
          attrs = { seq: seq }
          attrs[:payload] = JSON.generate(slide.payload_hash.merge(stamp: ctx.stamp)) if kind == "cover"
          slide.update_columns(attrs)
          next
        end
        built = builder_for(kind).build(ctx)
        Slide.create!(
          pitchbook_id: pitchbook.id, seq: seq, kind: kind,
          title: built[:title].presence || default_title,
          subtitle: built[:subtitle],
          payload: JSON.generate(built[:payload] || {}),
          is_pinned: false
        )
      end
      pitchbook.touch
    end
    pitchbook.slides.reset
    pitchbook.slides.to_a
  end

  def builder_for(kind)
    "Pitchbooks::Slides::#{kind.to_s.camelize}".constantize
  end

  # What the deck was built from (RAILS_PORT.md item 22): the data as-of date
  # (newest of the target's balance-sheet date and its newest document), the
  # price date, the build time and the code version.
  def stamp_for(metrics, comps = [])
    latest_document = Document.where(company_id: metrics[:company_id]).maximum(:published_at)
    corpus_document = Document.maximum(:published_at)
    balance_sheet = metrics[:net_debt_as_of]
    price_dates = MarketDatum.joins(:company).where(companies: { ticker: [metrics[:ticker], *comps] }).pluck(:as_of).compact
    {
      data_as_of: [balance_sheet, latest_document].compact.max,
      balance_sheet_date: balance_sheet,
      documents_as_of: latest_document,
      corpus_as_of: corpus_document,
      price_date: metrics[:as_of],
      peer_price_date: price_dates.max,
      built_at: Time.now.utc.iso8601,
      built_on: Date.current,
      code_version: code_version
    }
  end

  # `git rev-parse --short HEAD`, once per process. A checkout without git (a
  # packaged deploy) says "unknown" rather than failing the build.
  def code_version
    @code_version ||= begin
      out, status = Open3.capture2("git", "-C", Rails.root.to_s, "rev-parse", "--short", "HEAD", err: File::NULL)
      status.success? && out.strip.present? ? out.strip : "unknown"
    rescue StandardError
      "unknown"
    end
  end

  # Why the slides may be out of date (item 22): documents ingested or market
  # data repriced after the deck was last built (the stamp's build time, so an
  # edit that touches updated_at does not hide stale figures). Empty when the
  # deck is current. Financials carry no timestamps, so a reload shows up
  # through the market data the loader writes with it.
  def staleness(pitchbook)
    cover = pitchbook.slides.find { |s| s.kind == "cover" }
    stamp = cover&.payload_hash&.dig(:stamp) || {}
    built_at = (Time.iso8601(stamp[:built_at].to_s) rescue nil) || pitchbook.updated_at
    warnings = []
    fresh_documents = Document.where("created_at > ?", built_at).count
    if fresh_documents.positive?
      warnings << "#{fresh_documents} #{fresh_documents == 1 ? 'document was' : 'documents were'} added to the corpus after these slides were built."
    end
    tickers = [pitchbook.target_company&.ticker, *pitchbook.comp_tickers].compact
    stamped_price = stamp[:peer_price_date].presence || stamp[:price_date].presence
    newest_price = MarketDatum.joins(:company).where(companies: { ticker: tickers }).maximum(:as_of)
    if newest_price && (stamped_price.nil? || newest_price > Date.iso8601(stamped_price.to_s[0, 10]))
      warnings << "Market data is dated #{newest_price.iso8601}, newer than the deck's price date of #{stamped_price.presence || 'n/a'}."
    end
    warnings
  end

  # -------------------------------------------------------------------- reads

  # Index row (Python's list_pitchbooks).
  def summary(pitchbook)
    target = pitchbook.target_company
    {
      id: pitchbook.id, title: pitchbook.title, subtitle: pitchbook.subtitle,
      client_name: pitchbook.client_name, banker: pitchbook.banker, status: pitchbook.status,
      created_at: pitchbook.created_at, updated_at: pitchbook.updated_at,
      ticker: target&.ticker, target_name: target&.name,
      slide_count: pitchbook.slides.size, evidence_count: pitchbook.evidences.size
    }
  end

  def list
    Pitchbook.includes(:target_company, :slides, :evidences).order(updated_at: :desc, id: :desc).map { |book| summary(book) }
  end

  # The full deck as the API returns it (Python's get_pitchbook).
  def detail(pitchbook)
    target = pitchbook.target_company
    pitchbook.attributes.symbolize_keys.merge(
      ticker: target&.ticker, target_name: target&.name, sector: target&.sector,
      assumptions: pitchbook.assumptions_hash,
      slides: pitchbook.slides.reload.map { |slide| slide_hash(slide) },
      comps: pitchbook.comp_tickers,
      evidence: Slides::EvidenceAppendix.build_for(pitchbook)[:payload][:items]
                                        .map { |item| item.merge(pitchbook_id: pitchbook.id) }
    )
  end

  def slide_hash(slide)
    slide.attributes.symbolize_keys.merge(payload: slide.payload_hash, is_pinned: slide.is_pinned ? true : false)
  end

  # ------------------------------------------------------------------- writes

  # Edit a slide. Any edit pins it unless told otherwise (pin: false).
  # Accepts a Slide or an id; nil when the slide does not exist.
  def update_slide!(slide, title: nil, subtitle: nil, payload: nil, pin: nil)
    slide = Slide.find_by(id: slide) unless slide.is_a?(Slide)
    return nil unless slide

    attrs = {}
    attrs[:title] = title unless title.nil?
    attrs[:subtitle] = subtitle unless subtitle.nil?
    attrs[:payload] = JSON.generate(slide.payload_hash.merge(payload.to_h.deep_symbolize_keys)) unless payload.nil?
    attrs[:is_pinned] = pin.nil? || ActiveModel::Type::Boolean.new.cast(pin) ? true : false
    Slide.transaction do
      slide.update!(attrs)
      slide.pitchbook.touch
    end
    slide
  end

  def reorder_slides!(pitchbook, slide_ids)
    Slide.transaction do
      Array(slide_ids).each_with_index do |slide_id, seq|
        Slide.where(id: slide_id.to_i, pitchbook_id: pitchbook.id).update_all(seq: seq)
      end
      pitchbook.touch
    end
    pitchbook.slides.reset
    pitchbook.slides.to_a
  end

  # Move one slide up or down by one place (the UI's reorder buttons).
  def move_slide!(pitchbook, slide_id, direction)
    ids = pitchbook.slides.reload.map(&:id)
    index = ids.index(slide_id.to_i)
    return pitchbook.slides.to_a if index.nil?

    other = direction.to_s == "up" ? index - 1 : index + 1
    return pitchbook.slides.to_a if other.negative? || other >= ids.size

    ids[index], ids[other] = ids[other], ids[index]
    reorder_slides!(pitchbook, ids)
  end

  # Pin a passage from the research corpus onto a deck (optionally a slide).
  #
  # This is the join between the two halves of the product: the quote keeps its
  # document and chunk ids, so the appendix and every citation stay traceable.
  def add_evidence!(pitchbook, quote:, document_id: nil, chunk_id: nil, slide_id: nil, note: nil)
    quote = quote.to_s
    if chunk_id.present? && quote.strip.empty?
      chunk = Chunk.find_by(id: chunk_id)
      if chunk
        quote = chunk.text
        document_id = document_id.presence || chunk.document_id
      end
    end
    raise ArgumentError, "evidence requires a quote" if quote.strip.empty?
    # A citation that points nowhere is worse than none: refuse it rather than
    # letting the foreign key fail half way through.
    raise ArgumentError, "unknown document: #{document_id}" if document_id.present? && !Document.exists?(document_id)
    raise ArgumentError, "unknown chunk: #{chunk_id}" if chunk_id.present? && !Chunk.exists?(chunk_id)

    evidence = nil
    Evidence.transaction do
      evidence = Evidence.create!(
        pitchbook_id: pitchbook.id,
        slide_id: slide_id.presence,
        document_id: document_id.presence,
        chunk_id: chunk_id.presence,
        quote: quote.strip[0, QUOTE_LIMIT],
        note: note.presence
      )
      pitchbook.touch
    end
    refresh_evidence_slide!(pitchbook)
    evidence
  end

  def delete_evidence!(evidence)
    evidence = Evidence.find_by(id: evidence) unless evidence.is_a?(Evidence)
    return false unless evidence

    pitchbook = evidence.pitchbook
    evidence.destroy!
    refresh_evidence_slide!(pitchbook)
    true
  end

  # Keep the appendix in step with pinned evidence without a full rebuild.
  def refresh_evidence_slide!(pitchbook)
    slide = Slide.find_by(pitchbook_id: pitchbook.id, kind: "evidence_appendix")
    return if slide.nil? || slide.is_pinned

    built = Slides::EvidenceAppendix.build_for(pitchbook)
    slide.update_columns(title: built[:title], subtitle: built[:subtitle], payload: JSON.generate(built[:payload]))
  end

  def set_comps!(pitchbook, tickers)
    Pitchbook.transaction do
      CompMember.where(pitchbook_id: pitchbook.id, kind: "trading").delete_all
      write_comps(pitchbook, Array(tickers))
      rebuild_slides!(pitchbook)
    end
    pitchbook.comp_tickers
  end

  # Merge assumption overrides and rebuild. Blank values are ignored and the
  # merge rolls back if the rebuild rejects them (a terminal growth above WACC,
  # say), so a bad edit cannot leave a deck that no longer builds.
  def set_assumptions!(pitchbook, hash)
    merged = nil
    Pitchbook.transaction do
      merged = pitchbook.assumptions_hash.merge(clean_assumptions(hash))
      pitchbook.update!(assumptions: JSON.generate(merged))
      rebuild_slides!(pitchbook)
    end
    merged
  rescue ArgumentError, TypeError
    pitchbook.reload
    raise
  end

  # Delete a deck with its slides, comps and evidence. comp_members has no
  # primary key, so the children go with delete_all rather than callbacks.
  def delete!(pitchbook)
    Pitchbook.transaction do
      Evidence.where(pitchbook_id: pitchbook.id).delete_all
      Slide.where(pitchbook_id: pitchbook.id).delete_all
      CompMember.where(pitchbook_id: pitchbook.id).delete_all
      Pitchbook.where(id: pitchbook.id).delete_all.positive?
    end
  end

  # ------------------------------------------------------------------ helpers

  def write_comps(pitchbook, tickers)
    ids = Company.where(ticker: tickers.map { |t| t.to_s.strip.upcase }).where.not(id: pitchbook.target_company_id).pluck(:id).uniq
    return if ids.empty?

    CompMember.insert_all(ids.map { |id| { pitchbook_id: pitchbook.id, company_id: id, kind: "trading" } },
                          unique_by: %i[pitchbook_id company_id kind])
  end

  # Keep only known DCF fields with a value, cast to their types, so the form's
  # strings and the API's numbers persist the same way. Dates are stored as ISO.
  def clean_assumptions(hash)
    Valuation::DcfAssumptions.coerce(hash || {}).transform_values { |v| v.is_a?(Date) ? v.iso8601 : v }
  end

  private_class_method :write_comps
end
